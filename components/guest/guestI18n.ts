export function loadGuestLang(): GuestLang {
  try {
    const saved = localStorage.getItem('trace_guest_lang');
    if (saved === 'ru' || saved === 'uz' || saved === 'en') return saved;
  } catch { /* private mode */ }
  return navigator.language?.toLowerCase().startsWith('uz') ? 'uz' : 'ru';
}

export function saveGuestLang(l: GuestLang): void {
  try { localStorage.setItem('trace_guest_lang', l); } catch { /* private mode */ }
}

